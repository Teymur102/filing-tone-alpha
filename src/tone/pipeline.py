"""End-to-end pipeline. `python run.py` calls main(). Every step caches its output in data/."""
from __future__ import annotations

import json
import time

import numpy as np
import pandas as pd

from . import analysis as A
from . import config as C
from . import edgar, eventstudy, figures, lm, prices, text

TONE_PATH = C.DATA / "tone_scores.parquet"


def step(msg: str) -> float:
    print(f"\n== {msg}", flush=True)
    return time.time()


def load_events() -> pd.DataFrame:
    ev = edgar.build_filing_list()
    # acceptanceDateTime is UTC (releases cluster at 10-11h and 20-21h UTC = ~6-7am / ~4pm ET).
    # Convert to New York time so the 16:00 market-close rule handles daylight saving correctly.
    ev["accepted_et"] = (pd.to_datetime(ev["acceptanceDateTime"], utc=True)
                         .dt.tz_convert("America/New_York").dt.tz_localize(None))
    return ev


def score_tone(events: pd.DataFrame) -> pd.DataFrame:
    """LM + FinBERT tone for each exhibit. Resumable: finished documents are saved every 200."""
    done = pd.read_parquet(TONE_PATH) if TONE_PATH.exists() else pd.DataFrame(columns=["accessionNumber"])
    todo = events[~events.accessionNumber.isin(done.accessionNumber)]
    if todo.empty:
        return done
    from .finbert import FinBert, aggregate
    model = FinBert()
    pos, neg = lm.word_lists()
    print(f"  [tone] scoring {len(todo)} documents on {model.device}", flush=True)
    rows, t = [], time.time()
    for i, ev in enumerate(todo.itertuples(index=False), 1):
        sents = text.narrative_sentences(edgar.load_exhibit(ev.accessionNumber))[: C.MAX_SENTS_PER_DOC]
        row = {"accessionNumber": ev.accessionNumber, **lm.doc_tone(sents, pos, neg)}
        row.update(aggregate(model.predict(sents) if sents else np.zeros((0, 3)), model.label_index))
        rows.append(row)
        if i % 200 == 0 or i == len(todo):
            done = pd.concat([done, pd.DataFrame(rows)], ignore_index=True)
            done.to_parquet(TONE_PATH)
            rows = []
            print(f"  [tone] {i}/{len(todo)} docs, {time.time() - t:.0f}s", flush=True)
    return done


def size_control(panel: pd.DataFrame, px: pd.DataFrame) -> pd.Series:
    """log market cap at day -2 = unadjusted close x latest cover-page share count filed before the event."""
    unadj = prices.unadjusted_close(px)
    out = pd.Series(np.nan, index=panel.index)
    for (tkr, cik), g in panel.groupby(["ticker", "cik"]):
        sh = prices.shares_outstanding(int(cik))
        if sh.empty or tkr not in unadj:
            continue
        for idx, r in g.iterrows():
            avail = sh[sh.filed < r.day0]
            pdate = unadj.index[unadj.index < r.day0]
            if avail.empty or len(pdate) < 2:
                continue
            out[idx] = np.log(unadj[tkr].loc[pdate[-2]] * avail.shares.iloc[-1])
    return out


def write_tables(reg: pd.DataFrame, terc: pd.DataFrame, ports: pd.DataFrame) -> None:
    """Human-readable Markdown versions of the result CSVs (the README copies from here)."""
    lines = ["# Result tables (generated by run.py)", "",
             "## Regressions: CAR on tone (coefficient in bp of CAR per 1 s.d. of tone; t in parentheses)", "",
             "Controls: log market cap, 12-1 momentum, prior 20-day return; drift windows also control for CAR[0,+1].",
             "Calendar-quarter fixed effects; SEs two-way clustered by firm and quarter.", "",
             "| Tone measure | CAR[0,+1] | CAR[+2,+20] | CAR[+2,+60] | N |", "|---|---|---|---|---|"]
    for spec in reg.spec.unique():
        for x in spec.split("+"):
            cells = []
            for w in C.CAR_WINDOWS:
                r = reg[(reg.spec == spec) & (reg.y == w)].iloc[0]
                cells.append(f"{r[f'b_{x}'] * 1e4:+.1f} ({r[f't_{x}']:+.2f})")
            label = A.SIGNAL_LABELS[x] + (" [joint model]" if "+" in spec else "")
            lines.append(f"| {label} | " + " | ".join(cells) + f" | {int(r['n'])} |")
    lines += ["", "## Tercile sorts: mean CAR (%) by tone tercile (trailing 365-day breakpoints)", "",
              "| Signal | Window | Low | Mid | High | High-Low | t (quarter-clustered) |", "|---|---|---|---|---|---|---|"]
    for r in terc.itertuples():
        lines.append(f"| {r.signal} | {r.window} | {r.low * 100:.2f} | {r.mid * 100:.2f} | {r.high * 100:.2f} | "
                     f"{r.high_minus_low * 100:+.2f} | {r.t_stat:+.2f} |")
    lines += ["", f"## Calendar-time long-short drift portfolio (days +2..+60; costs {C.COST_BPS_PER_SIDE} bp per side)", "",
              "| Signal | Period | Ann. return gross | t (NW) | Ann. return net | t (NW) | Sharpe net | CAPM alpha net (t) |",
              "|---|---|---|---|---|---|---|---|"]
    for r in ports.itertuples():
        lines.append(f"| {r.signal}{' (chosen)' if r.chosen else ''} | {r.period} | {r.ann_ret_gross:+.1%} | "
                     f"{r.nw_t_gross:+.2f} | {r.ann_ret_net:+.1%} | {r.nw_t_net:+.2f} | {r.sharpe_net:+.2f} | "
                     f"{r.capm_alpha_net_ann:+.1%} ({r.capm_alpha_net_t:+.2f}) |")
    (C.RESULTS / "tables.md").write_text("\n".join(lines) + "\n")


def main() -> None:
    t_all = time.time()
    for d in (C.DATA, C.RESULTS, C.FIGURES):
        d.mkdir(parents=True, exist_ok=True)

    t = step("1/6 EDGAR: 8-K Item 2.02 earnings releases")
    events = load_events()
    print(f"  {len(events)} events, {events.ticker.nunique()} firms ({time.time() - t:.0f}s)")

    t = step("2/6 Tone: Loughran-McDonald + FinBERT")
    tone = score_tone(events)
    print(f"  done ({time.time() - t:.0f}s)")

    t = step("3/6 Prices and market-model abnormal returns")
    px = prices.download_prices(C.TICKERS)
    rets = prices.returns_matrix(px)
    cars, paths = eventstudy.run(events, rets)
    panel = events.merge(tone, on="accessionNumber").merge(cars, on="accessionNumber")
    panel = panel[panel.n_sents >= 5].copy()        # need some prose to measure tone
    panel["log_mcap"] = size_control(panel, px)
    panel["yq"] = panel["day0"].dt.to_period("Q").astype(str)
    panel = A.add_tone_changes(panel)
    for c in [*C.CAR_WINDOWS, "mom_12_1", "ret_pre20"]:
        panel[c] = A.winsorize(panel[c])
    print(f"  panel: {len(panel)} events with tone and CARs ({time.time() - t:.0f}s)")

    t = step("4/6 Cross-sectional regressions")
    base = ["log_mcap", "mom_12_1", "ret_pre20"]
    specs = []
    for w in C.CAR_WINDOWS:
        ctrl = base if w == "car_0_1" else base + ["car_0_1"]   # day 0-1 reaction = surprise proxy
        for xs in (["lm_tone"], ["finbert_tone"], ["lm_tone", "finbert_tone"],
                   ["lm_tone_chg"], ["finbert_tone_chg"]):
            specs.append({"spec": "+".join(xs), **A.regress(panel, w, xs, ctrl)})
    reg = pd.DataFrame(specs)
    reg.to_csv(C.RESULTS / "regressions.csv", index=False)
    print(reg[["y", "spec", "n"] + [c for c in reg.columns if c.startswith("t_") and "tone" in c]].round(2).to_string())

    t = step("5/6 Tercile sorts and out-of-sample trading test")
    terc_tables = []
    for s in A.SIGNALS:
        panel[f"terc_{s}"] = A.trailing_terciles(panel, s)
        tt = A.tercile_table(panel, f"terc_{s}")
        tt.insert(0, "signal", s)
        terc_tables.append(tt)
    terc = pd.concat(terc_tables, ignore_index=True)
    terc.to_csv(C.RESULTS / "tercile_cars.csv", index=False)
    print(terc.round(4).to_string())

    # Choose the signal on the training period only, by the [+2,+60] high-minus-low t-stat.
    train = panel[panel.day0 <= C.TRAIN_END]
    train_t = {s: A.tercile_table(train, f"terc_{s}").set_index("window").loc["car_2_60", "t_stat"]
               for s in A.SIGNALS}
    chosen = max(train_t, key=train_t.get)
    test_start = (pd.Timestamp(C.TRAIN_END) + pd.Timedelta(days=1)).strftime("%Y-%m-%d")
    port_rows, port_series = [], {}
    for s in A.SIGNALS:
        for label, a, b in (("train", "2018-01-01", C.TRAIN_END), ("test", test_start, C.SAMPLE_END)):
            p = A.calendar_portfolio(panel, rets, f"terc_{s}", a, b)
            port_rows.append({"signal": s, "period": label, "chosen": s == chosen, **A.portfolio_stats(p, f"{s}/{label}")})
            port_series[(s, label)] = p
    ports = pd.DataFrame(port_rows)
    ports.to_csv(C.RESULTS / "portfolio_stats.csv", index=False)
    print(f"  training-period t-stats (car_2_60, high-low): { {k: round(v, 2) for k, v in train_t.items()} }")
    print(f"  chosen signal: {chosen}")
    print(ports[["signal", "period", "ann_ret_gross", "nw_t_gross", "ann_ret_net", "nw_t_net", "sharpe_net"]].round(3).to_string())

    t = step("6/6 Figures and summary")
    corr = panel[["lm_tone", "finbert_tone"]].corr().iloc[0, 1]
    spear = panel[["lm_tone", "finbert_tone"]].corr(method="spearman").iloc[0, 1]
    corr_chg = panel[["lm_tone_chg", "finbert_tone_chg"]].corr().iloc[0, 1]
    both = panel.dropna(subset=["terc_lm_tone", "terc_finbert_tone"])
    agree = float((both.terc_lm_tone == both.terc_finbert_tone).mean())
    figures.car_paths(panel, paths)
    figures.agreement(panel, corr, spear, agree)
    figures.oos_equity(port_series[(chosen, "test")], chosen)

    test_row = ports[(ports.signal == chosen) & (ports.period == "test")].iloc[0]
    summary = {
        "n_events": int(len(panel)), "n_firms": int(panel.ticker.nunique()),
        "first_event": str(panel.day0.min().date()), "last_event": str(panel.day0.max().date()),
        "n_events_downloaded": int(len(events)),
        "median_sentences_per_doc": float(panel.n_sents.median()),
        "corr_lm_finbert_pearson": corr, "corr_lm_finbert_spearman": spear,
        "corr_lm_finbert_change": corr_chg, "tercile_agreement_lm_finbert": agree,
        "train_t_stats_car_2_60": train_t, "chosen_signal": chosen,
        "oos_chosen": {k: (v.item() if hasattr(v, "item") else str(v)) for k, v in test_row.items()},
        "after_close_share": float((panel.accepted_et.dt.hour >= 16).mean()),
        "runtime_seconds": round(time.time() - t_all),
    }
    (C.RESULTS / "summary.json").write_text(json.dumps(summary, indent=2, default=str))
    write_tables(reg, terc, ports)
    panel.drop(columns=["exhibit_url"]).to_csv(C.RESULTS / "event_panel.csv.gz", index=False)
    print(json.dumps(summary, indent=2, default=str))
    print(f"\nTotal runtime {time.time() - t_all:.0f}s")
